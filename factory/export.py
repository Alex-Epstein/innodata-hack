"""Export validated task sets as a product pack a lab can consume (product/DATASHEET.md).

    uv run python -m factory export --tasks tasks/pilot_topo_crossings --tasks tasks/pilot_topo_sunset \
        --tasks tasks/pilot_topo_flood --format rl --out product/sample_pack

Format `rl` writes an RL environment pack with verifiable rewards:
    envs.jsonl      one environment per task: prompt (exactly as eval sends it), image, reward_spec, metadata
    verifier.py     self-contained reward(env, model_output) -> 1.0 or 0.0; eval/scoring.py is vendored verbatim
    sft.jsonl       process-supervised examples: prompt + image + a worked solution built in code from `steps`
    images/         the PNGs the prompts refer to
    MANIFEST.json   counts per mission and difficulty, generator versions, license, SHA-256 of every file

Only tasks that passed every validate/ check are exported; anything else is listed in MANIFEST.json as dropped.
Every worked solution is scored by the vendored verifier before it is written; a solution that does not score
1.0 stops the export.
"""
from __future__ import annotations

import hashlib
import importlib.util
import inspect
import json
import shutil
from collections import Counter
from pathlib import Path

from eval import scoring
from factory.tasks import load_tasks

LICENSE = {
    "pack": "Task text, answers, worked solutions and images generated by this factory; the team's own work.",
    "terrain": "Elevation from the USGS 3D Elevation Program (3DEP), public domain (US Government work), via AWS "
               "Open Data Terrain Tiles; gen/topo/tiles/SOURCES.md lists every tile URL and checksum.",
}
PARTIAL = 0.5

# ---------------------------------------------------------------------------------------------- verifier.py
VERIFIER_HEAD = '''"""Reward function for this RL environment pack. Self-contained: standard library only.

    from verifier import reward, load_envs
    envs = load_envs("envs.jsonl")
    r = reward(envs[0], model_output)              # 1.0 or 0.0, the official exact score
    r = reward(envs[0], model_output, shaped=True)  # optional partial credit, see below

    python verifier.py            # self-test: every env's reference answer scores 1.0

OFFICIAL SCORING IS EXACT. `reward(env, out)` is 1.0 when the text after the last "FINAL ANSWER:" in `out`
matches the reference under the same rules the factory's evaluation uses (eval/scoring.py, vendored verbatim
below), and 0.0 otherwise. Every number we report uses this exact reward.

OPTIONAL SHAPING (`shaped=True`), for RL training only. It looks only at the final answer, never at the
reasoning, and gives 0.5 when the answer equals one of `reward_spec.shaping.near_values`:
  - crossings: the count is off by exactly one contour line (reference +/- 1).
  - sunset: off by exactly one uphill contour line (reference +/- minutes_per_uphill_contour), or the right
    magnitude with the sign flipped (the climb count was right, the subtraction was turned around).
    "Uphill count right, arithmetic wrong" in general cannot be read from the answer alone, so it is not shaped.
  - flood (a campsite name) and every other task: no shaping, exact only.
Known wrong methods (`reward_spec.shaping.trap_values`, e.g. leaving out index contours, ignoring the climb)
always score 0.0, even if they happen to fall next to the reference.
"""
from __future__ import annotations

# ---------------------------------------------------------------------------------------------------------
# Vendored verbatim from eval/scoring.py (the factory's evaluation scorer)
# ---------------------------------------------------------------------------------------------------------
'''

VERIFIER_TAIL = '''

# ---------------------------------------------------------------------------------------------------------
# Pack API
# ---------------------------------------------------------------------------------------------------------
def _as_task(env: dict) -> dict:
    spec = env["reward_spec"]
    task = {"task_id": env.get("env_id"), "answer_type": spec["answer_type"], "answer": spec["reference"]}
    for k in ("tolerance_abs", "tolerance_rel", "options", "ordered"):
        if spec.get(k) is not None:
            task[k] = spec[k]
    return task


def reward(env: dict, model_output: str, shaped: bool = False) -> float:
    """1.0 if the model's FINAL ANSWER is correct (exact, as in the official evaluation), else 0.0.
    With shaped=True, 0.5 for a near miss listed in reward_spec.shaping (see the module docstring)."""
    parsed = parse_final_answer(model_output or "")
    if score(parsed, _as_task(env)):
        return 1.0
    shaping = env["reward_spec"].get("shaping") or {}
    if not shaped or not shaping.get("near_values") or parsed == "":
        return 0.0
    x = to_number(parsed)
    if x is None or x in [float(v) for v in shaping.get("trap_values", [])]:
        return 0.0
    return float(shaping.get("partial_credit", 0.5)) if x in [float(v) for v in shaping["near_values"]] else 0.0


def load_envs(path) -> list:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


if __name__ == "__main__":
    import os
    import sys
    here = os.path.dirname(os.path.abspath(__file__))
    envs = load_envs(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "envs.jsonl"))
    bad = [e["env_id"] for e in envs
           if reward(e, "FINAL ANSWER: " + ref_answer_cell(e["reward_spec"]["reference"])) != 1.0
           or reward(e, "no answer here") != 0.0]
    print(f"{len(envs) - len(bad)}/{len(envs)} environments: reference scores 1.0, empty reply 0.0")
    sys.exit(1 if bad else 0)
'''


def verifier_source() -> str:
    body = inspect.getsource(scoring).replace("from __future__ import annotations\n", "", 1)
    return VERIFIER_HEAD + body + VERIFIER_TAIL


def load_verifier(path: Path):
    spec = importlib.util.spec_from_file_location(f"pack_verifier_{abs(hash(str(path)))}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# ---------------------------------------------------------------------------------------------- helpers
def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _hhmm(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def _compass(deg: float) -> str:
    names = ["north", "north-northeast", "northeast", "east-northeast", "east", "east-southeast", "southeast",
             "south-southeast", "south", "south-southwest", "southwest", "west-southwest", "west",
             "west-northwest", "northwest", "north-northwest"]
    return names[int((deg % 360) / 22.5 + 0.5) % 16]


def _mission(r: dict) -> str:
    return r.get("template") or r.get("question_type", "").split(".", 1)[-1]


def _region(data: dict) -> str | None:
    d = data.get("data", {}) if isinstance(data.get("data"), dict) else {}
    if d.get("area"):
        return ", ".join(x for x in (d.get("area"), d.get("state")) if x)
    return None


def _all_checks_pass(r: dict) -> bool:
    checks = r.get("checks")
    return bool(checks) and all(checks.values())


# ---------------------------------------------------------------------------------------------- reward spec
def reward_spec(r: dict, data: dict) -> dict:
    spec = {"answer_type": r["answer_type"], "reference": r["answer"], "scoring": "exact"}
    for k in ("tolerance_abs", "tolerance_rel", "options", "ordered"):
        if r.get(k) is not None:
            spec[k] = r[k]
    if r["answer_type"] == "sequence" and "ordered" not in spec:
        spec["ordered"] = True
    steps, mission, ref = r.get("steps") or {}, _mission(r), r["answer"]
    near, traps, why = [], [], ""
    if r.get("family") == "topo" and mission == "crossings" and r["answer_type"] == "integer":
        near = [ref - 1, ref + 1]
        traps = [steps.get("wrong_if_index_contours_left_out")]
        why = "count off by exactly one contour line"
    elif r.get("family") == "topo" and mission == "sunset" and r["answer_type"] == "integer":
        per = data["data"]["mission"]["minutes_per_uphill_contour"]
        near = [ref - per, ref + per] + ([-ref] if ref != 0 else [])
        traps = [steps.get("wrong_if_every_crossing_counted"), steps.get("wrong_if_climb_ignored")]
        why = (f"off by exactly one uphill contour line ({per} min), or the right magnitude with the sign flipped")
    traps = sorted({t for t in traps if t is not None and t != ref})
    near = [v for v in near if v not in traps and v != ref]
    if near:
        spec["shaping"] = {"partial_credit": PARTIAL, "near_values": near, "trap_values": traps, "why": why,
                           "note": "optional, for training only; the official score is exact"}
    return spec


# ---------------------------------------------------------------------------------------------- worked solutions
def _solution_crossings(r: dict, d: dict) -> list[str]:
    s, ci, idx = r["steps"], d["contour_interval_m"], d["index_interval_m"]
    levels = s["levels_crossed"]
    idx_levels = [lv for lv in levels if lv % idx == 0]
    lines = [
        f"Step 1. Read the map key: contour lines every {ci} m; the heavy, labeled index contours every {idx} m. "
        f"Every line counts, index lines included.",
        f"Step 2. Find the {d['trail']['name']} (solid magenta line) and trace it from S to E, noting each contour "
        f"line it crosses and that line's elevation (from the index labels and the {ci} m spacing):",
    ]
    lines += [f"  {i}. {lv} m line" + (" (index contour)" if lv % idx == 0 else "") for i, lv in enumerate(levels, 1)]
    lines.append(f"Step 3. Of these, {len(idx_levels)} are index contours"
                 + (f" ({', '.join(str(x) for x in idx_levels)} m)" if idx_levels else "")
                 + f". Leaving them out would give {s['wrong_if_index_contours_left_out']}, which undercounts.")
    lines.append(f"Step 4. Check by direction: {s['uphill_crossings']} crossings going uphill and "
                 f"{s['downhill_crossings']} going downhill, {s['uphill_crossings']} + {s['downhill_crossings']} = "
                 f"{s['contour_crossings']}. Lines crossed twice are counted twice.")
    lines.append(f"The trail crosses {s['contour_crossings']} contour lines between S and E.")
    return lines


def _solution_sunset(r: dict, d: dict) -> list[str]:
    s, m, ci = r["steps"], d["mission"], d["contour_interval_m"]
    per = m["minutes_per_uphill_contour"]
    ans = r["answer"]
    return [
        f"Step 1. Read the incident box: now {_hhmm(m['now_min'])}, sunset {_hhmm(m['sunset_min'])}, so "
        f"{s['daylight_minutes']} minutes of daylight are left. Walking the {d['trail']['name']} on flat ground "
        f"takes {s['flat_walk_min']} minutes.",
        f"Step 2. The contour interval is {ci} m. Trace the trail (solid magenta line) from S to H and use the "
        f"index contour labels to tell up from down: it crosses {s['uphill_crossings']} contour lines going "
        f"uphill and {s['downhill_crossings']} going downhill.",
        f"Step 3. Naismith's rule as stated: {per} minutes per uphill line, so the climb adds {per} x "
        f"{s['uphill_crossings']} = {s['minutes_for_ascent']} minutes. Downhill lines add nothing.",
        f"Step 4. Walking time = {s['flat_walk_min']} + {s['minutes_for_ascent']} = {s['walking_minutes']} "
        f"minutes, so the hiker arrives at {s['arrival']}.",
        f"Step 5. Minutes before sunset = {s['daylight_minutes']} - {s['walking_minutes']} = {ans}"
        + (" (negative: the hiker arrives after dark)." if ans < 0 else "."),
    ]


def _solution_flood(r: dict, d: dict) -> list[str]:
    s, ci = r["steps"], d["contour_interval_m"]
    lo = int(s["dam_elev_m"] // ci * ci)
    flooded = s["flooded_camp"]
    lines = [
        f"Step 1. The contour interval is {ci} m. The dam D stands at about {s['dam_elev_m']:.0f} m, between the "
        f"{lo} m and {lo + ci} m contour lines.",
        f"Step 2. Water leaves D in the direction of steepest descent, at right angles to the contours: it sets "
        f"off heading about {s['water_sets_off_bearing_deg']} degrees ({_compass(s['water_sets_off_bearing_deg'])}).",
        f"Step 3. Follow it downhill, crossing every contour line at a right angle and turning as the lines turn. "
        f"The route runs about {s['water_route_length_m']:.0f} m.",
        "Step 4. Compare each campsite with the route:",
    ]
    for c in s["camps"]:
        where = "on the route" if c["flooded"] else f"{c['distance_to_water_route_m']:.0f} m off the route"
        lines.append(f"  {c['camp']}: {c['elev_m']:.0f} m elevation, {where}.")
    decoys = []
    for key, what in (("dry_camp_most_directly_below_dam", "lies most directly in the water's first direction"),
                      ("nearest_campsite_to_dam", "is nearest the dam"), ("lowest_campsite", "is the lowest")):
        c = s.get(key)
        if c and c != flooded:
            decoys.append(f"{c} {what}")
    if decoys:
        lines.append("Step 5. Rule out the shortcuts: " + "; ".join(decoys) + ". None of these is on the route, "
                     "because the water follows the slope around its bends.")
    lines.append(f"Only {flooded} lies in the water's path.")
    return lines


def _solution_generic(r: dict, d: dict) -> list[str]:
    steps = r.get("steps") or {}
    items = [f"{k.replace('_', ' ')}: {json.dumps(v, ensure_ascii=False)}" for k, v in steps.items()] \
        if isinstance(steps, dict) else [str(x) for x in steps]
    return [f"Step {i}. {x}" for i, x in enumerate(items, 1)] or ["Read the figure and apply the rule in the question."]


SOLVERS = {"crossings": _solution_crossings, "sunset": _solution_sunset, "flood": _solution_flood}


def worked_solution(r: dict, data: dict) -> str:
    d = data.get("data", {})
    fn = SOLVERS.get(_mission(r)) if r.get("family") == "topo" else None
    lines = (fn or _solution_generic)(r, d)
    return "\n".join(lines) + f"\nFINAL ANSWER: {scoring.ref_answer_cell(r['answer'])}"


# ---------------------------------------------------------------------------------------------- export
def export_rl(task_dirs: list[str | Path], out: str | Path) -> dict:
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    (out / "images").mkdir(parents=True)
    (out / "verifier.py").write_text(verifier_source(), encoding="utf-8")
    verifier = load_verifier(out / "verifier.py")

    envs, sft, dropped, sources = [], [], [], []
    for tdir in map(Path, task_dirs):
        records = load_tasks(tdir)
        sources.append({"tasks": str(tdir), "records": len(records)})
        for r in records:
            if not _all_checks_pass(r):
                failed = [k for k, v in (r.get("checks") or {}).items() if not v] or ["not validated"]
                dropped.append({"task_id": r["task_id"], "source": str(tdir), "failed": failed})
                continue
            data = json.loads((tdir / r["data"]).read_text(encoding="utf-8")) if r.get("data") else {}
            image = f"images/{Path(r['image']).name}"
            shutil.copy2(tdir / r["image"], out / image)
            prompt = scoring.build_prompt(r["question"])
            env = {"env_id": r["task_id"], "family": r.get("family"), "mission": _mission(r),
                   "question_type": r.get("question_type"), "prompt": prompt, "image": image,
                   "reward_spec": reward_spec(r, data), "difficulty": r.get("difficulty"),
                   "region": _region(data), "seed": r.get("seed"), "generator_version": r.get("generator_version"),
                   "checks_passed": sorted(k for k, v in r["checks"].items() if v),
                   "image_sha256": sha256(out / image), "references": r.get("references", [])}
            solution = worked_solution(r, data)
            if verifier.reward(env, solution) != 1.0 or verifier.reward(env, "FINAL ANSWER:") != 0.0:
                raise SystemExit(f"{r['task_id']}: the worked solution does not verify; export stopped")
            envs.append(env)
            sft.append({"env_id": r["task_id"], "image": image, "prompt": prompt, "completion": solution,
                        "messages": [{"role": "user", "content": [{"type": "image", "image": image},
                                                                  {"type": "text", "text": prompt}]},
                                     {"role": "assistant", "content": solution}],
                        "supervision": "process: every intermediate value is computed from the task data in code"})

    def write_jsonl(name, rows):
        with open(out / name, "w", encoding="utf-8") as f:
            for row in rows:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")

    write_jsonl("envs.jsonl", envs)
    write_jsonl("sft.jsonl", sft)

    files = sorted(p for p in out.rglob("*") if p.is_file())
    manifest = {
        "pack": "RL environment pack: terrain reasoning on topographic maps",
        "format": "rl",
        "environments": len(envs),
        "sft_examples": len(sft),
        "by_mission": dict(sorted(Counter(e["mission"] for e in envs).items())),
        "by_difficulty": {str(k): v for k, v in sorted(Counter(e["difficulty"] for e in envs).items())},
        "by_mission_and_difficulty": {f"{m}/{dif}": n for (m, dif), n in
                                      sorted(Counter((e["mission"], e["difficulty"]) for e in envs).items())},
        "by_region": dict(sorted(Counter(e["region"] or "n/a" for e in envs).items())),
        "generator_versions": sorted({e["generator_version"] for e in envs if e["generator_version"]}),
        "scoring": "exact (verifier.reward); optional 0.5 shaping on crossings and sunset near misses",
        "admission": "only tasks that passed every validate/ check are exported",
        "dropped": dropped,
        "sources": sources,
        "license": LICENSE,
        "sha256": {str(p.relative_to(out)): sha256(p) for p in files},
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return manifest


def cmd_export(a) -> int:
    if a.format != "rl":
        raise SystemExit(f"unknown format {a.format!r} (available: rl)")
    m = export_rl(a.tasks, a.out)
    print(f"{m['environments']} environments, {m['sft_examples']} SFT examples, {len(m['dropped'])} dropped "
          f"-> {a.out}  (by mission: {m['by_mission']})")
    return 0 if m["environments"] else 1


def add_parser(sub) -> None:
    x = sub.add_parser("export", help="package validated task sets as a product pack (RL envs + verifier + SFT)")
    x.add_argument("--tasks", action="append", required=True, help="task folder; repeatable")
    x.add_argument("--format", default="rl", choices=["rl"], help="rl: envs.jsonl + verifier.py + sft.jsonl")
    x.add_argument("--out", required=True, help="pack folder, e.g. product/sample_pack (replaced)")
    x.set_defaults(fn=cmd_export)
